import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { execFileSync } from "node:child_process";

const root = resolve(import.meta.dirname, "..");
const dist = join(root, "dist");
const build = join(root, ".build");
const bundlePath = join(build, "deepseek2response.bundle.js");
const seaConfigPath = join(build, "sea-config.json");
const exePath = join(dist, "deepseek2response.exe");

rmSync(build, { recursive: true, force: true });
mkdirSync(build, { recursive: true });
mkdirSync(dist, { recursive: true });
rmSync(join(dist, "Start DeepSeek2Response Exe.cmd"), { force: true });

const modules = new Map();
collectModule("src/server.js");

let bundle = `// Generated by scripts/build-standalone.js\n`;
bundle += `const __modules = {};\n`;
for (const [modulePath, source] of modules) {
  bundle += `__modules[${JSON.stringify(modulePath)}] = (exports) => {\n${source}\n};\n`;
}
bundle += `
const __cache = {};
function __load(id) {
  if (__cache[id]) return __cache[id];
  const exports = {};
  __cache[id] = exports;
  __modules[id](exports);
  return exports;
}
const main = __load("src/server.js");
main.startStandalone();
`;

writeFileSync(bundlePath, bundle);
writeFileSync(seaConfigPath, JSON.stringify({ main: bundlePath, output: exePath }, null, 2));
execFileSync(process.execPath, [`--build-sea=${seaConfigPath}`], { stdio: "inherit" });
copyFileSync(join(root, ".env.example"), join(dist, ".env.example"));
copyFileSync(join(root, "codex-config.example.toml"), join(dist, "codex-config.example.toml"));
copyFileSync(join(root, "README.md"), join(dist, "README.md"));
writeFileSync(join(dist, "Start DeepSeek2Response.cmd"), `@echo off
setlocal
cd /d "%~dp0"

if not exist ".env" (
  echo Missing .env. Copy .env.example to .env and set DEEPSEEK_API_KEY.
  pause
  exit /b 1
)

deepseek2response.exe
pause
`);

function collectModule(relativePath) {
  const normalized = normalizePath(relativePath);
  if (modules.has(normalized)) {
    return;
  }

  const absolutePath = join(root, normalized);
  const source = readFileSync(absolutePath, "utf8");
  const imports = [...source.matchAll(/^import\s+(?:\{([^}]+)\}\s+from\s+)?["'](\.\/[^"']+)["'];?$/gm)];
  const exportedNames = [];
  let transformed = source;

  for (const match of imports) {
    const importTarget = match[2].endsWith(".js") ? match[2] : `${match[2]}.js`;
    const importedPath = normalizePath(join(dirname(normalized), importTarget));
    collectModule(importedPath);

    const names = match[1]
      .split(",")
      .map((name) => name.trim())
      .filter(Boolean)
      .join(", ");
    transformed = transformed.replace(match[0], `const { ${names} } = __load(${JSON.stringify(importedPath)});`);
  }

  transformed = transformed
    .replace(/^import\s+([^"'\n]+)\s+from\s+["'](node:[^"']+)["'];?$/gm, "const $1 = require('$2');")
    .replace(/^import\s+\{\s*([^}]+)\s*\}\s+from\s+["'](node:[^"']+)["'];?$/gm, "const { $1 } = require('$2');")
    .replace(/^export\s+class\s+(\w+)/gm, (_, name) => {
      exportedNames.push(name);
      return `class ${name}`;
    })
    .replace(/^export\s+async\s+function\s+(\w+)/gm, (_, name) => {
      exportedNames.push(name);
      return `async function ${name}`;
    })
    .replace(/^export\s+function\s+(\w+)/gm, (_, name) => {
      exportedNames.push(name);
      return `function ${name}`;
    });

  transformed = transformed
    .replace(/const isDirectRun = .*?;\n\nif \(isDirectRun\) \{\n  startStandalone\(\);\n\}\n/s, "")
    .replace(/typeof __DEEPSEEK2RESPONSE_BUNDLE__ === "undefined" && /g, "");

  if (exportedNames.length > 0) {
    transformed += `\n${exportedNames.map((name) => `exports.${name} = ${name};`).join("\n")}\n`;
  }

  modules.set(normalized, transformed);
}

function normalizePath(path) {
  return path.replaceAll("\\", "/").replace(/^\.\//, "");
}
